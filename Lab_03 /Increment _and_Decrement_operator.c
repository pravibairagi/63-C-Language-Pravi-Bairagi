#include<stdio.h>
int main ()
{
    int x = 5 ;

    printf("The Initial Value of x: %d\n ", x );
    
    printf("Postfix Increment ( x++ ) : %d\n ", x++ );

    printf("Prefix Increment ( ++x ): %d\n\n", ++x ); 

    printf("Prefix Decrement ( --x ): %d\n\n", --x );   

    printf("Postfix Decrement ( x-- ): %d\n\n", x-- ); 
    

    return 0 ;

} 
